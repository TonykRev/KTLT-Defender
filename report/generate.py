"""
M12 - Generate Chapter 4 tables from db/results.sqlite (Owner: Opus).

Reads the measurement DB and emits Markdown tables + CSVs for Chapter 4:
  4.1 Axis A (static) detection by variant
  4.2 Axis B behavioural detection by technique
  4.3 Detection summary (counts, rate, by layer, latency)
  4.4 Cloud-ON / ASR spot-check delta
  4.5 Supplementary-rule false-positive rate

Run from repo root:  python report/generate.py
(If db/results.sqlite is absent, run report/reconstruct_db.py first.)
"""
from __future__ import annotations
import csv
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

DB_PATH = "db/results.sqlite"
OUT_DIR = "report/out"


def _run_by_note(conn, like):
    row = conn.execute("SELECT run_id FROM runs WHERE notes LIKE ?", (f"%{like}%",)).fetchone()
    return row[0] if row else None


def _rows(conn, run_id, axis):
    return conn.execute(
        "SELECT scenario_group, technique_id, variant, state, detection_layer, detect_latency_ms, "
        "error_message FROM measurements WHERE run_id=? AND axis=? ORDER BY measurement_id",
        (run_id, axis)).fetchall()


def _md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join("" if c is None else str(c) for c in r) + " |")
    return "\n".join(out)


def _write_csv(path, headers, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(headers)
        w.writerows(rows)


def generate_report(db_path: str = DB_PATH, out_dir: str = OUT_DIR) -> str:
    conn = sqlite3.connect(db_path)
    os.makedirs(out_dir, exist_ok=True)
    md = ["# Chapter 4 - Measurement Results (auto-generated)",
          "", "_Generated by report/generate.py from db/results.sqlite._", ""]

    run_a = _run_by_note(conn, "Axis A")
    run_b = _run_by_note(conn, "Axis B baseline")
    run_c = _run_by_note(conn, "cloud-ON")
    run_d = _run_by_note(conn, "ASR spot-check")

    # --- 4.1 Axis A ---
    md += ["## Table 4.1 - Axis A (static/signature) detection by payload variant", ""]
    a_rows = [(v, st, (ly or "-"), (note or "")) for _, _, v, st, ly, _, note in _rows(conn, run_a, "static")]
    md += [_md_table(["Variant", "State", "Layer", "Note"], a_rows), ""]
    _write_csv(os.path.join(out_dir, "table_4_1_axis_a.csv"),
               ["variant", "state", "layer", "note"], a_rows)

    # --- 4.2 Axis B ---
    md += ["## Table 4.2 - Axis B (behavioural) detection by technique", ""]
    b = _rows(conn, run_b, "behavior")
    b_rows = [(g, t, st, (ly or "-"), ("" if lat is None else lat)) for g, t, _, st, ly, lat, _ in b]
    md += [_md_table(["Group", "Technique", "State", "Layer", "Latency (ms)"], b_rows), ""]
    _write_csv(os.path.join(out_dir, "table_4_2_axis_b.csv"),
               ["group", "technique", "state", "layer", "latency_ms"], b_rows)

    # --- 4.3 Summary ---
    det = [r for r in b if r[3] == "detected"]
    nd = [r for r in b if r[3] == "not_detected"]
    total = len(b)
    layers = {}
    for r in det:
        layers[r[4] or "unknown"] = layers.get(r[4] or "unknown", 0) + 1
    md += ["## Table 4.3 - Axis B detection summary", "",
           f"- Techniques measured: **{total}**",
           f"- Detected / blocked by Defender: **{len(det)}** "
           f"({', '.join(r[1] for r in det)})",
           f"- Not detected (gaps): **{len(nd)}**",
           f"- Detection rate: **{(100.0*len(det)/total):.1f}%**" if total else "- Detection rate: n/a",
           f"- Detecting layers: " + ", ".join(f"{k} ({v})" for k, v in sorted(layers.items())),
           ""]

    # --- 4.4 Spot-check delta ---
    def _state_map(run_id):
        return {t: st for _, t, _, st, _, _, _ in _rows(conn, run_id, "behavior")}
    base, con, asr = _state_map(run_b), _state_map(run_c), _state_map(run_d)
    delta_rows = []
    for t in sorted(con):
        delta_rows.append((t, base.get(t, "-"), con.get(t, "-"),
                           asr.get(t, "-") if t in asr else "-"))
    md += ["## Table 4.4 - Cloud-ON / ASR spot-check (delta vs baseline)", ""]
    md += [_md_table(["Technique", "Baseline (cloud-OFF)", "Cloud-ON", "ASR-ON"], delta_rows), ""]
    flips = sum(1 for t, b0, c0, _ in delta_rows if b0 == "not_detected" and c0 == "detected")
    md += [f"- Cloud-ON delta (not_detected -> detected): **{flips} / "
           f"{sum(1 for _, b0, _, _ in delta_rows if b0 == 'not_detected')}**", ""]
    _write_csv(os.path.join(out_dir, "table_4_4_spotcheck.csv"),
               ["technique", "baseline", "cloud_on", "asr_on"], delta_rows)

    # --- 4.5 Rule FP ---
    fp = conn.execute("SELECT rule_name, rule_type, goodware_total, false_positives, fp_rate "
                      "FROM rule_fp ORDER BY rule_fp_id").fetchall()
    md += ["## Table 4.5 - Supplementary-rule false-positive rate (goodware)", ""]
    fp_rows = [(n, ty, tot, fps, f"{(rate or 0)*100:.3f}%") for n, ty, tot, fps, rate in fp]
    md += [_md_table(["Rule", "Type", "Goodware files", "False positives", "FP rate"], fp_rows), ""]
    _write_csv(os.path.join(out_dir, "table_4_5_rule_fp.csv"),
               ["rule", "type", "goodware_total", "false_positives", "fp_rate"], fp)

    conn.close()
    out_md = os.path.join(out_dir, "chapter4_tables.md")
    with open(out_md, "w", encoding="utf-8") as f:
        f.write("\n".join(md) + "\n")
    return out_md


if __name__ == "__main__":
    path = generate_report()
    print(f"Wrote {path} (+ CSVs in {OUT_DIR}/)")
